export function currentCategory(item: ReadingItem, sources: WorkbenchHost['sources'], categories: SourceCategory[]): { id: string; name: string } {
  const source = sources.find(source => item.sourceId ? source.registry_id === item.sourceId : source.display_name === item.source || source.original_name === item.source);
  const id = source?.categoryId ?? item.categoryId ?? item.topic;
  const category = categories.find(category => category.id === id);
  return { id, name: category?.name ?? item.categoryName ?? topicLabels[item.topic] };
}
